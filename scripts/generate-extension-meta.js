import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, cpSync, rmSync } from 'fs';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const extensionsDir = resolve(__dirname, '..', 'extensions');
const publicExtensionsDir = resolve(__dirname, '..', 'public', 'extensions');
const metaOutputPath = resolve(__dirname, '..', 'extensions-meta.json');
const jsOutputPath = resolve(__dirname, '..', 'public', 'builtin-extensions.js');

// 工作台以 `/extensions/<name>/...` 读取内置扩展资源（图标主题、语法、片段等），
// 该路径相对前端根目录，因此需要把扩展目录同步进 public/ 随构建产物一起提供。
function mirrorExtensionResources(dirNames) {
  rmSync(publicExtensionsDir, { recursive: true, force: true });
  for (const dirName of dirNames) {
    cpSync(join(extensionsDir, dirName), join(publicExtensionsDir, dirName), { recursive: true });
  }
  console.log(`Mirrored ${dirNames.length} extension resource directories to public/extensions`);
}

function writeBuiltinExtensions(descriptors) {
  writeFileSync(metaOutputPath, JSON.stringify(descriptors, null, 2));
  console.log(`Wrote ${descriptors.length} extension descriptors to extensions-meta.json`);

  const jsContent = `// Auto-generated by scripts/generate-extension-meta.js — do not edit
(function() {
  var meta = document.createElement('meta');
  meta.id = 'vscode-workbench-builtin-extensions';
  meta.setAttribute('data-settings', JSON.stringify(${JSON.stringify(descriptors)}));
  document.head.appendChild(meta);
})();
`;

  writeFileSync(jsOutputPath, jsContent);
  console.log(`Wrote public/builtin-extensions.js (${(jsContent.length / 1024).toFixed(1)} KB)`);
}

if (!existsSync(extensionsDir)) {
  console.warn(`Extensions directory not found: ${extensionsDir}`);
  console.warn(`Continuing with built-in theme fallbacks. Run "npm run setup:full" to include the full VS Code extension catalog.`);
  writeBuiltinExtensions([]);
  process.exit(0);
}

// SideX keeps only declarative extensions for the file manager/editor core.
// Extensions for removed features (Git/SCM, chat/AI prompts, notebooks) are
// skipped so their settings do not leak into the settings editor.
const SKIPPED_EXTENSIONS = new Set([
  'git',
  'git-base',
  'github',
  'github-authentication',
  'TypeScriptTeam.jsts-chat-features',
  'copilot',
  'copilot-chat',
  'notebook-renderers',
  'prompt-basics'
]);

const entries = readdirSync(extensionsDir);
const descriptors = [];

for (const dirName of entries) {
  if (SKIPPED_EXTENSIONS.has(dirName)) continue;

  const dirPath = join(extensionsDir, dirName);
  if (!statSync(dirPath).isDirectory()) continue;

  const pkgPath = join(dirPath, 'package.json');
  if (!existsSync(pkgPath)) continue;

  let packageJSON;
  try {
    packageJSON = JSON.parse(readFileSync(pkgPath, 'utf-8'));
  } catch (err) {
    console.warn(`Skipping ${dirName}: failed to parse package.json — ${err.message}`);
    continue;
  }

  let packageNLS = undefined;
  const nlsPath = join(dirPath, 'package.nls.json');
  if (existsSync(nlsPath)) {
    try {
      packageNLS = JSON.parse(readFileSync(nlsPath, 'utf-8'));
    } catch {
      // nls is optional, ignore parse errors
    }
  }

  const descriptor = { extensionPath: dirName, packageJSON };
  if (packageNLS) descriptor.packageNLS = packageNLS;
  descriptors.push(descriptor);
}

descriptors.sort((a, b) => a.extensionPath.localeCompare(b.extensionPath));

writeBuiltinExtensions(descriptors);
mirrorExtensionResources(descriptors.map(descriptor => descriptor.extensionPath));
